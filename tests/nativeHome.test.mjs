import test from "node:test";
import assert from "node:assert/strict";
import { readHistory, recordView, recordRestaurantVisit, getRecentItems, getRecentRestaurants, HISTORY_STORAGE_KEY } from "../lib/history/browsingHistory.ts";
import { recordQuery, readRecentQueries, RECENT_QUERIES_KEY } from "../lib/search/recentQueries.ts";
import { formatRelativeTime } from "../lib/formatRelativeTime.ts";
import { buildCalorieSegments } from "../components/nutrition/macroSegments.ts";
const storage = new Map();
globalThis.window = { localStorage: { getItem: key => storage.get(key) ?? null, setItem: (key,value) => storage.set(key,value) }, dispatchEvent() {} };
test("history migrates visits, deduplicates views, caps entries and unions restaurant activity", () => {
  storage.clear();
  storage.set("recentlySearchedRestaurants", JSON.stringify(["chickfila", "chipotle"]));
  assert.deepEqual(getRecentRestaurants().map(r => r.restaurantId), ["chickfila", "chipotle"]);
  recordView({ restaurantId: "chipotle", kind: "builder-entree", refId: "bowl" });
  recordView({ restaurantId: "chickfila", kind: "menu-item", refId: "sandwich" });
  recordView({ restaurantId: "chickfila", kind: "menu-item", refId: "sandwich" });
  assert.equal(readHistory().entries.length, 2);
  assert.equal(getRecentItems().length, 1);
  recordRestaurantVisit("starbucks");
  assert.ok(getRecentRestaurants().some(r => r.restaurantId === "starbucks"));
  for (let i=0; i<45; i++) recordView({ restaurantId: "chickfila", kind: "menu-item", refId: `${i}` });
  assert.equal(readHistory().entries.length, 40);
  assert.equal(getRecentItems().length, 8);
  storage.set(HISTORY_STORAGE_KEY, '{broken');
  assert.deepEqual(readHistory().entries, []);
  storage.set(HISTORY_STORAGE_KEY, JSON.stringify({ version: 1, entries: [null, { kind: "bad" }], visits: [null] }));
  assert.deepEqual(readHistory().entries, []);
  storage.set(HISTORY_STORAGE_KEY, JSON.stringify({ version: 9, entries: [] }));
  assert.deepEqual(readHistory().visits, []);
});
test("queries trim, dedupe case insensitively, limit and tolerate corrupt/blocked storage", () => {
  storage.clear();
  recordQuery(" a "); assert.deepEqual(readRecentQueries(), []);
  recordQuery(" Chicken "); recordQuery("CHICKEN");
  assert.deepEqual(readRecentQueries(), ["CHICKEN"]);
  for (let i=0;i<7;i++) recordQuery(`query ${i}`);
  assert.equal(readRecentQueries().length, 5);
  assert.equal(readRecentQueries()[0], "query 6");
  storage.set(RECENT_QUERIES_KEY, '[null,4," valid ","VALID"]');
  assert.deepEqual(readRecentQueries(), ["valid"]);
  storage.set(RECENT_QUERIES_KEY, 'bad'); assert.deepEqual(readRecentQueries(), []);
  const original = window.localStorage;
  window.localStorage = { getItem() { throw Error(); }, setItem() { throw Error(); } };
  assert.doesNotThrow(() => recordQuery("chicken"));
  assert.doesNotThrow(() => recordRestaurantVisit("chipotle"));
  window.localStorage = original;
});
test("calorie shares use 4/4/9 and round to 100, including ties and zeros", () => {
  assert.deepEqual(buildCalorieSegments({ protein:64, carbs:93, fat:53 }).map(s => s.roundedPercent), [23,34,43]);
  assert.deepEqual(buildCalorieSegments({ protein:0, carbs:0, fat:0 }).map(s => s.roundedPercent), [0,0,0]);
  for (const macros of [{protein:1,carbs:1,fat:1}, {protein:3,carbs:3,fat:0}, {protein:0,carbs:0,fat:5}]) assert.equal(buildCalorieSegments(macros).reduce((sum,s) => sum+s.roundedPercent,0),100);
});
test("relative times follow local calendar days", () => {
  const now = new Date(2026,9,19,12).getTime();
  assert.equal(formatRelativeTime(now,now), "Just now");
  assert.equal(formatRelativeTime(now-2*60_000,now), "2m ago");
  assert.equal(formatRelativeTime(now-2*3_600_000,now), "2h ago");
  assert.equal(formatRelativeTime(new Date(2026,9,18,23).getTime(),now), "Yesterday");
  assert.equal(formatRelativeTime(new Date(2026,9,16,12).getTime(),now), "3d ago");
  assert.equal(formatRelativeTime(new Date(2026,9,12,12).getTime(),now), "Oct 12");
  assert.equal(formatRelativeTime(now+1000,now), "Just now");
});
test("history cards resolve actual native items and reject missing default nutrition", async () => {
  const { resolveHistoryEntry, hasCompleteDefaultNutrition } = await import("../components/native/home/historyPresentation.ts");
  const { loadSearchIndex } = await import("../lib/search/searchIndex.ts");
  const index = await loadSearchIndex();
  const source = index.find(s => s.restaurant.id === "chickfila");
  const item = source.items.find(i => hasCompleteDefaultNutrition(i));
  assert.ok(resolveHistoryEntry({ restaurantId: "chickfila", kind: "menu-item", refId: item.id, viewedAt: 0 }, index)?.item);
  assert.equal(resolveHistoryEntry({ restaurantId: "missing", kind: "menu-item", refId: "x", viewedAt: 0 }, index), null);
  assert.equal(hasCompleteDefaultNutrition({ ...item, variants: [], nutrition: { calories: 2 } }), false);
  const builder = index.find(s => s.restaurant.id === "chipotle").entreeBuilders[0];
  assert.match(resolveHistoryEntry({ restaurantId: "chipotle", kind: "builder-entree", refId: builder.entreeId, viewedAt: 0 }, index).href, /view=ingredients/);
});
